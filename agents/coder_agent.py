def mock_doubao_call(system_prompt: str, user_message: str) -> str:
    """
    Simulate a ByteDance Doubao API call.

    In production replace the body of this function with:

        import openai  # Doubao is OpenAI-API-compatible
        client = openai.OpenAI(
            api_key=os.environ["DOUBAO_API_KEY"],
            base_url="https://ark.cn-beijing.volces.com/api/v3",
        )
        response = client.chat.completions.create(
            model="doubao-pro-128k",
            messages=[
                {"role": "system", "content": system_prompt},
                {"role": "user",   "content": user_message},
            ],
        )
        return response.choices[0].message.content

    The mock inspects the spec JSON embedded in ``user_message`` and returns
    realistic C code that covers all common peripheral templates.
    """
    # Extract the JSON spec from the user message.
    # Use a JSONDecoder that stops at the end of the first complete object,
    # ignoring any trailing prose that follows the spec in the prompt.
    spec: HardwareSpec = {}
    try:
        json_start = user_message.index("{")
        decoder = json.JSONDecoder()
        spec, _ = decoder.raw_decode(user_message, json_start)
    except (ValueError, json.JSONDecodeError):
        spec = {}

    mcu: str = spec.get("mcu", "ESP32")
    rtos: str = spec.get("rtos", "FreeRTOS")
    peripherals: list = spec.get("peripherals", [])
    tasks: list = spec.get("tasks", [])
    memory: dict = spec.get("memory", {})

    interface = (peripherals[0].get("interface", "GPIO") if peripherals else "GPIO").upper()
    task_name = tasks[0].get("name", "main_task") if tasks else "main_task"
    stack_size = tasks[0].get("stack_size", 4096) if tasks else 4096
    priority = tasks[0].get("priority", 5) if tasks else 5
    period_ms = tasks[0].get("period_ms", 1000) if tasks else 1000
    heap_kb = memory.get("heap_kb", 16)

    # ------------------------------------------------------------------ I2C / OLED
    if interface == "I2C":
        pins = peripherals[0].get("pins", {}) if peripherals else {}
        sda = pins.get("SDA", "GPIO_NUM_21")
        scl = pins.get("SCL", "GPIO_NUM_22")
        i2c_addr = peripherals[0].get("address", "0x3C") if peripherals else "0x3C"

