class CoderAgent:
    """
    Generates production-quality C/C++ source code from a ``HardwareSpec``.

    Parameters
    ----------
    llm_backend:
        Callable with signature ``(system_prompt: str, user_message: str) -> str``
        that returns C/C++ source code as a plain string.
        Defaults to ``mock_doubao_call``.
    """

    SYSTEM_PROMPT = (
        "You are a senior Embedded Systems Software Engineer with deep expertise in "
        "ESP-IDF, STM32 HAL, and FreeRTOS.  "
        "You will receive a JSON hardware specification and MUST produce a complete, "
        "compilable C source file.  "
        "Requirements:\n"
        "  1. Include all necessary headers.\n"
        "  2. Use FreeRTOS primitives (xTaskCreate, vTaskDelay, semaphores, queues).\n"
        "  3. Guard every heap allocation (pvPortMalloc / malloc) with a NULL check.\n"
        "  4. Every FreeRTOS task function must call vTaskDelete(NULL) before returning.\n"
        "  5. Use mutex/semaphore to protect shared peripheral resources.\n"
        "  6. Follow MISRA-C naming conventions.\n"
        "  7. Do NOT include prose — return ONLY the C source code."
    )

    def __init__(self, llm_backend=None):
        self._llm = llm_backend or mock_doubao_call

    # ------------------------------------------------------------------
    def generate(self, spec: HardwareSpec, previous_feedback: Optional[str] = None) -> str:
        """
        Generate (or regenerate) C/C++ source code.

        Parameters
        ----------
        spec:
            Hardware specification from the Planner Agent.
        previous_feedback:
            Reviewer feedback from the previous iteration (if any).
            When provided, the LLM is instructed to fix the identified issues.

        Returns
        -------
        str
            Complete C/C++ source code as a plain string.
        """
        spec_json = json.dumps(spec, indent=2)

        if previous_feedback:
            user_message = (
                f"Hardware Specification:\n{spec_json}\n\n"
                f"IMPORTANT — The previous version of this code FAILED review with "
                f"the following feedback. You MUST address every point:\n\n"
                f"{previous_feedback}\n\n"
                f"Generate a corrected version of the complete C source file."
            )
        else:
            user_message = (
                f"Hardware Specification:\n{spec_json}\n\n"
                f"Generate the complete C source file."
            )

        return self._llm(self.SYSTEM_PROMPT, user_message)
