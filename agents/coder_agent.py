"""
coder_agent.py
==============
Role: Coder Agent
Responsibility:
    Consumes a ``HardwareSpec`` produced by the Planner Agent and generates
    production-quality C/C++ source code that follows either the ESP-IDF or
    STM32 HAL library conventions, wrapped with FreeRTOS task primitives.

LLM backend
-----------
Real deployments should replace ``mock_doubao_call`` with an authenticated
call to the ByteDance Doubao (or equivalent) API.  The mock returns
syntactically complete C code that the Reviewer Agent can analyse.

Output contract
---------------
A single string containing the complete C/C++ source file, ready to be
written to disk as ``<task_name>.c``.
"""

